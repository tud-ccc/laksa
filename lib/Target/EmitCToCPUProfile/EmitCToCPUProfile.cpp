#include "llvm/ADT/STLExtras.h"
#include "llvm/Support/raw_ostream.h"

using namespace mlir;
using namespace mlir::laksa;

namespace {

struct NodeArg {
    emitc::ArrayType type;
    std::string elementType;
    std::string name;
};

struct Node {
    std::string name;
    SmallVector<NodeArg> args;
    std::string runnerName;
};

bool isOutlinedNodeName(StringRef name)
{
    size_t marker = name.rfind("_node_");
    if (marker == StringRef::npos) return false;
    StringRef number = name.drop_front(marker + StringRef("_node_").size());
    return !number.empty()
           && number.find_first_not_of("0123456789") == StringRef::npos;
}

FailureOr<std::string> getCElementType(Type type)
{
    if (auto intTy = dyn_cast<IntegerType>(type)) {
        unsigned width = intTy.getWidth();
        if (width == 1) return std::string("bool");
        if (width == 8 || width == 16 || width == 32 || width == 64)
            return (intTy.isUnsigned() ? std::string("uint")
                                       : std::string("int"))
                   + std::to_string(width) + "_t";
    }
    if (isa<Float32Type>(type)) return std::string("float");
    if (isa<Float64Type>(type)) return std::string("double");
    return failure();
}

void emitArraySuffix(raw_ostream &os, emitc::ArrayType type)
{
    for (int64_t extent : type.getShape()) os << '[' << extent << ']';
}

void emitCall(raw_ostream &os, const Node &node, StringRef indent)
{
    os << indent << node.name << '(';
    llvm::interleaveComma(node.args, os, [&](const NodeArg &arg) {
        os << arg.name;
    });
    os << ");\n";
}

} // namespace

LogicalResult
laksa::translateEmitCToCPUProfile(ModuleOp module, raw_ostream &os)
{
    SmallVector<Node> nodes;
    unsigned nodeIndex = 0;
    for (emitc::FuncOp func : module.getOps<emitc::FuncOp>()) {
        if (func.isExternal() || !isOutlinedNodeName(func.getSymName()))
            continue;

        Node node{
            func.getSymName().str(),
            {},
            "measureNode" + std::to_string(nodeIndex)};
        Block &body = func.getFunctionBody().front();
        for (auto [argIndex, blockArg] : llvm::enumerate(body.getArguments())) {
            auto arrayType = dyn_cast<emitc::ArrayType>(blockArg.getType());
            if (!arrayType)
                return func.emitError(
                           "CPU profiling only supports array "
                           "arguments; argument ")
                       << argIndex << " has type " << blockArg.getType();
            FailureOr<std::string> elementType =
                getCElementType(arrayType.getElementType());
            if (failed(elementType))
                return func.emitError("argument ")
                       << argIndex << " has an unsupported element type "
                       << arrayType.getElementType();
            node.args.push_back(
                NodeArg{
                    arrayType,
                    *elementType,
                    "node" + std::to_string(nodeIndex) + "Arg"
                        + std::to_string(argIndex)});
        }
        nodes.push_back(std::move(node));
        ++nodeIndex;
    }

    if (nodes.empty())
        return module.emitError(
            "expected at least one non-external emitc.func to benchmark");

    os << "// Generated by ladle --cpu-profile.\n"
          "// Compile together with nodes.cpp on the target CPU.\n\n"
          "#include <algorithm>\n"
          "#include <cerrno>\n"
          "#include <cstddef>\n"
          "#include <cstdint>\n"
          "#include <cstdio>\n"
          "#include <cstdlib>\n"
          "#include <cstring>\n"
          "#include <iostream>\n"
          "#include <linux/perf_event.h>\n"
          "#include <string>\n"
          "#include <sys/ioctl.h>\n"
          "#include <sys/syscall.h>\n"
          "#include <unistd.h>\n"
          "#include <utility>\n"
          "#include <vector>\n\n";

    for (const Node &node : nodes) {
        os << "void " << node.name << '(';
        llvm::interleaveComma(node.args, os, [&](const NodeArg &arg) {
            os << arg.elementType << ' ' << arg.name;
            emitArraySuffix(os, arg.type);
        });
        os << ");\n";
    }

    os << "\nnamespace {\n\n"
          "volatile std::uint64_t checksumSink = 0;\n\n"
          "[[noreturn]] void fail(const char *message)\n"
          "{\n"
          "    std::perror(message);\n"
          "    std::exit(EXIT_FAILURE);\n"
          "}\n\n"
          "int openCycleCounter()\n"
          "{\n"
          "    perf_event_attr attr{};\n"
          "    attr.type = PERF_TYPE_HARDWARE;\n"
          "    attr.size = sizeof(attr);\n"
          "    attr.config = PERF_COUNT_HW_CPU_CYCLES;\n"
          "    attr.disabled = 1;\n"
          "    attr.exclude_kernel = 1;\n"
          "    attr.exclude_hv = 1;\n"
          "    int fd = static_cast<int>(syscall(\n"
          "        SYS_perf_event_open, &attr, 0, -1, -1, 0));\n"
          "    if (fd == -1) {\n"
          "        std::fprintf(\n"
          "            stderr,\n"
          "            \"cannot open the CPU cycle counter: %s\\n\"\n"
          "            \"Try running ./run.sh with sufficient perf-event \"\n"
          "            \"permissions.\\n\",\n"
          "            std::strerror(errno));\n"
          "        std::exit(EXIT_FAILURE);\n"
          "    }\n"
          "    return fd;\n"
          "}\n\n"
          "template <typename Function>\n"
          "std::uint64_t countCycles(Function &&function, unsigned "
          "repetitions)\n"
          "{\n"
          "    int fd = openCycleCounter();\n"
          "    if (ioctl(fd, PERF_EVENT_IOC_RESET, 0) == -1) fail(\"counter "
          "reset\");\n"
          "    if (ioctl(fd, PERF_EVENT_IOC_ENABLE, 0) == -1) fail(\"counter "
          "enable\");\n"
          "    for (unsigned i = 0; i < repetitions; ++i) function();\n"
          "    if (ioctl(fd, PERF_EVENT_IOC_DISABLE, 0) == -1) fail(\"counter "
          "disable\");\n"
          "    std::uint64_t cycles = 0;\n"
          "    if (read(fd, &cycles, sizeof(cycles)) != sizeof(cycles)) "
          "fail(\"counter read\");\n"
          "    close(fd);\n"
          "    return (cycles + repetitions / 2) / repetitions;\n"
          "}\n\n"
          "void fillBuffer(void *data, std::size_t size, std::uint64_t seed)\n"
          "{\n"
          "    auto *bytes = static_cast<unsigned char *>(data);\n"
          "    std::uint64_t state = seed ? seed : 1;\n"
          "    for (std::size_t i = 0; i < size; ++i) {\n"
          "        state ^= state << 13;\n"
          "        state ^= state >> 7;\n"
          "        state ^= state << 17;\n"
          "        bytes[i] = static_cast<unsigned char>(state);\n"
          "    }\n"
          "}\n\n"
          "std::uint64_t checksum(const void *data, std::size_t size)\n"
          "{\n"
          "    const auto *bytes = static_cast<const unsigned char *>(data);\n"
          "    std::uint64_t value = 1469598103934665603ULL;\n"
          "    for (std::size_t i = 0; i < size; ++i)\n"
          "        value = (value ^ bytes[i]) * 1099511628211ULL;\n"
          "    return value;\n"
          "}\n\n";

    for (const Node &node : nodes)
        for (const NodeArg &arg : node.args) {
            os << "alignas(64) static " << arg.elementType << ' ' << arg.name;
            emitArraySuffix(os, arg.type);
            os << "{};\n";
        }

    os << '\n';
    for (auto [index, node] : llvm::enumerate(nodes)) {
        os << "std::uint64_t " << node.runnerName
           << "(unsigned warmup, unsigned repetitions, unsigned samples)\n"
              "{\n"
              "    static bool initialized = false;\n"
              "    if (!initialized) {\n";
        for (auto [argIndex, arg] : llvm::enumerate(node.args))
            os << "        fillBuffer(" << arg.name << ", sizeof(" << arg.name
               << "), " << (index + 1) * 1009 + argIndex << ");\n";
        os << "        initialized = true;\n"
              "    }\n"
              "    for (unsigned i = 0; i < warmup; ++i)\n";
        emitCall(os, node, "        ");
        os << "    std::vector<std::uint64_t> measurements;\n"
              "    measurements.reserve(samples);\n"
              "    for (unsigned sample = 0; sample < samples; ++sample) {\n"
              "        measurements.push_back(countCycles([&] {\n";
        emitCall(os, node, "            ");
        os << "        }, repetitions));\n"
              "    }\n"
              "    std::sort(measurements.begin(), measurements.end());\n";
        for (const NodeArg &arg : node.args)
            os << "    checksumSink ^= checksum(" << arg.name << ", sizeof("
               << arg.name << "));\n";
        os << "    return measurements[measurements.size() / 2];\n"
              "}\n\n";
    }

    os << "struct Options {\n"
          "    unsigned warmup = 1;\n"
          "    unsigned repetitions = 3;\n"
          "    unsigned samples = 5;\n"
          "    std::string node;\n"
          "    std::string processorType = \"CortexA53\";\n"
          "};\n\n"
          "unsigned parseCount(const char *flag, const char *value, bool "
          "allowZero)\n"
          "{\n"
          "    char *end = nullptr;\n"
          "    errno = 0;\n"
          "    unsigned long parsed = std::strtoul(value, &end, 10);\n"
          "    if (errno || !end || *end || (!allowZero && parsed == 0)) {\n"
          "        std::fprintf(stderr, \"%s expects %s integer, got "
          "'%s'\\n\",\n"
          "                     flag, allowZero ? \"a non-negative\" : \"a "
          "positive\", value);\n"
          "        std::exit(EXIT_FAILURE);\n"
          "    }\n"
          "    return static_cast<unsigned>(parsed);\n"
          "}\n\n"
          "Options parseOptions(int argc, char **argv)\n"
          "{\n"
          "    Options options;\n"
          "    for (int i = 1; i < argc; ++i) {\n"
          "        std::string flag = argv[i];\n"
          "        if (flag == \"--help\") {\n"
          "            std::cout << \"Usage: benchmark [--node NAME] [--warmup "
          "N] \"\n"
          "                         \"[--repetitions N] [--samples N] \"\n"
          "                         \"[--processor-type NAME]\\n\";\n"
          "            std::exit(EXIT_SUCCESS);\n"
          "        }\n"
          "        if (i + 1 >= argc) {\n"
          "            std::fprintf(stderr, \"%s requires a value\\n\", "
          "flag.c_str());\n"
          "            std::exit(EXIT_FAILURE);\n"
          "        }\n"
          "        const char *value = argv[++i];\n"
          "        if (flag == \"--node\") options.node = value;\n"
          "        else if (flag == \"--warmup\")\n"
          "            options.warmup = parseCount(flag.c_str(), value, "
          "true);\n"
          "        else if (flag == \"--repetitions\")\n"
          "            options.repetitions = parseCount(flag.c_str(), value, "
          "false);\n"
          "        else if (flag == \"--samples\")\n"
          "            options.samples = parseCount(flag.c_str(), value, "
          "false);\n"
          "        else if (flag == \"--processor-type\") "
          "options.processorType = value;\n"
          "        else {\n"
          "            std::fprintf(stderr, \"unknown option: %s\\n\", "
          "flag.c_str());\n"
          "            std::exit(EXIT_FAILURE);\n"
          "        }\n"
          "    }\n"
          "    return options;\n"
          "}\n\n"
          "void printQuoted(const std::string &value)\n"
          "{\n"
          "    std::cout << '\"';\n"
          "    for (char c : value) {\n"
          "        if (c == '\\\\' || c == '\"') std::cout << '\\\\';\n"
          "        std::cout << c;\n"
          "    }\n"
          "    std::cout << '\"';\n"
          "}\n\n"
          "} // namespace\n\n"
          "int main(int argc, char **argv)\n"
          "{\n"
          "    Options options = parseOptions(argc, argv);\n"
          "    std::vector<std::pair<std::string, std::uint64_t>> results;\n";

    for (const Node &node : nodes) {
        os << "    if (options.node.empty() || options.node == \"" << node.name
           << "\")\n"
           << "        results.emplace_back(\"" << node.name << "\", "
           << node.runnerName
           << "(options.warmup, options.repetitions, options.samples));\n";
    }

    os << "    if (results.empty()) {\n"
          "        std::fprintf(stderr, \"unknown node: %s\\n\", "
          "options.node.c_str());\n"
          "        return EXIT_FAILURE;\n"
          "    }\n"
          "    std::cout << \"execution:\\n  processes:\\n    profiles:\\n\";\n"
          "    for (const auto &[name, cycles] : results) {\n"
          "        std::cout << \"      \";\n"
          "        printQuoted(name);\n"
          "        std::cout << \":\\n        \";\n"
          "        printQuoted(options.processorType);\n"
          "        std::cout << \": {cycles: \" << cycles << \"}\\n\";\n"
          "    }\n"
          "    return EXIT_SUCCESS;\n"
          "}\n";

    return success();
}

LogicalResult
laksa::translateEmitCToCPUProfileNodes(ModuleOp module, raw_ostream &os)
{
    os << "// Generated by ladle --cpu-profile.\n"
          "#include <algorithm>\n"
          "#include <cstddef>\n"
          "#include <cstdint>\n\n";
    return emitc::translateToCpp(module, os);
}
